def prism(poly_xy: np.ndarray, height: float) -> np.ndarray:
    """Closed triangle mesh of a convex polygon extruded from z=0 to z=height (CCW polygon)."""
    n = len(poly_xy)
    bot = np.c_[poly_xy, np.zeros(n)]
    top = np.c_[poly_xy, np.full(n, height)]
    tris = []
    for i in range(1, n - 1):
        tris.append([top[0], top[i], top[i + 1]])
        tris.append([bot[0], bot[i + 1], bot[i]])
    for i in range(n):
        j = (i + 1) % n
        tris.append([bot[i], bot[j], top[j]])
        tris.append([bot[i], top[j], top[i]])
    return np.array(tris, float)


def box(lo, hi) -> np.ndarray:
    (x0, y0, z0), (x1, y1, z1) = lo, hi
    t = prism(np.array([[x0, y0], [x1, y0], [x1, y1], [x0, y1]]), z1 - z0)
    t[:, :, 2] += z0
    return t


def chamfered_rect(w, d, c):
    hw, hd = w / 2, d / 2
    return np.array([[-hw + c, -hd], [hw - c, -hd], [hw, -hd + c], [hw, hd - c], [hw - c, hd], [-hw + c, hd],
                     [-hw, hd - c], [-hw, -hd + c]])


def write_binary(path: Path, tris: np.ndarray, header: str):
    path.write_bytes(am.stl_bytes(tris, header))


def write_ascii(path: Path, tris: np.ndarray, name: str):
    lines = [f"solid {name}"]
    for t in tris:
        n = np.cross(t[1] - t[0], t[2] - t[0])
        n = n / (np.linalg.norm(n) or 1)
        lines.append(f"  facet normal {n[0]:.6e} {n[1]:.6e} {n[2]:.6e}")
        lines.append("    outer loop")
        for v in t:
            lines.append(f"      vertex {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}")
        lines.append("    endloop")
        lines.append("  endfacet")
    lines.append(f"endsolid {name}")
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


